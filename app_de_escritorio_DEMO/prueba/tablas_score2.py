def obtener_rango_edad(edad, score_type='score2'):
    if score_type == 'score2':
        if 40 <= edad <= 44: return '40-44'
        if 45 <= edad <= 49: return '45-49'
        if 50 <= edad <= 54: return '50-54'
        if 55 <= edad <= 59: return '55-59'
        if 60 <= edad <= 64: return '60-64'
        if 65 <= edad <= 69: return '65-69'
    else:
        if 70 <= edad <= 74: return '70-74'
        if 75 <= edad <= 79: return '75-79'
        if 80 <= edad <= 84: return '80-84'
        if 85 <= edad <= 89: return '85-89'
    return None

def obtener_rango_pas(pas):
    if 100 <= pas <= 119: return '100-119'
    if 120 <= pas <= 139: return '120-139'
    if 140 <= pas <= 159: return '140-159'
    if 160 <= pas <= 179: return '160-179'
    return None

def obtener_indice_colesterol(col_no_hdl):
    if 3.0 <= col_no_hdl < 4.0: return 0
    if 4.0 <= col_no_hdl < 5.0: return 1
    if 5.0 <= col_no_hdl < 6.0: return 2
    if 6.0 <= col_no_hdl <= 7.0: return 3
    return None

def obtener_tabla(sexo, fumador, edad, region='moderado'):
    score_type = 'score2op' if edad >= 70 else 'score2'

    if region == 'moderado':
        if score_type == 'score2':
            if sexo == 'varon':
                return SCORE2_MODERADO_VARONES_FUMADORES if fumador else SCORE2_MODERADO_VARONES_NO_FUMADORES
            else:
                return SCORE2_MODERADO_MUJERES_FUMADORAS if fumador else SCORE2_MODERADO_MUJERES_NO_FUMADORAS
        else:
            if sexo == 'varon':
                return SCORE2OP_MODERADO_VARONES_FUMADORES if fumador else SCORE2OP_MODERADO_VARONES_NO_FUMADORES
            else:
                return SCORE2OP_MODERADO_MUJERES_FUMADORAS if fumador else SCORE2OP_MODERADO_MUJERES_NO_FUMADORAS

    elif region == 'muy_alto':
        if score_type == 'score2':
            if sexo == 'varon':
                return SCORE2_MUY_ALTO_VARONES_FUMADORES if fumador else SCORE2_MUY_ALTO_VARONES_NO_FUMADORES
            else:
                return SCORE2_MUY_ALTO_MUJERES_FUMADORAS if fumador else SCORE2_MUY_ALTO_MUJERES_NO_FUMADORAS
        else:
            if sexo == 'varon':
                return SCORE2OP_MUY_ALTO_VARONES_FUMADORES if fumador else SCORE2OP_MUY_ALTO_VARONES_NO_FUMADORES
            else:
                return SCORE2OP_MUY_ALTO_MUJERES_FUMADORAS if fumador else SCORE2OP_MUY_ALTO_MUJERES_NO_FUMADORAS

    return None

def calcular_riesgo(edad, sexo, fumador, pas, col_no_hdl, region='moderado', interpolar=False):
    score_type = 'score2op' if edad >= 70 else 'score2'

    if score_type == 'score2' and not (40 <= edad <= 69):
        return {'error': 'Edad fuera de rango para SCORE2 (40-69 años)'}
    if score_type == 'score2op' and not (70 <= edad <= 89):
        return {'error': 'Edad fuera de rango para SCORE2-OP (70-89 años)'}

    rango_edad = obtener_rango_edad(edad, score_type)
    rango_pas = obtener_rango_pas(pas)

    if not all([rango_edad, rango_pas]):
        return {'error': 'Valores fuera de rango permitido'}

    tabla = obtener_tabla(sexo, fumador, edad, region)
    if not tabla:
        return {'error': 'No se encontró la tabla correspondiente'}

    try:
        if interpolar and 3.0 <= col_no_hdl <= 7.0:
            if col_no_hdl < 4.0:
                indice_bajo, indice_alto = 0, 0
                factor = 0
            elif col_no_hdl < 5.0:
                indice_bajo, indice_alto = 0, 1
                factor = (col_no_hdl - 4.0) / 1.0
            elif col_no_hdl < 6.0:
                indice_bajo, indice_alto = 1, 2
                factor = (col_no_hdl - 5.0) / 1.0
            elif col_no_hdl < 7.0:
                indice_bajo, indice_alto = 2, 3
                factor = (col_no_hdl - 6.0) / 1.0
            else:
                indice_bajo, indice_alto = 3, 3
                factor = 0

            valor_bajo = tabla[rango_edad][rango_pas][indice_bajo]
            valor_alto = tabla[rango_edad][rango_pas][indice_alto]
            riesgo = int(valor_bajo + (valor_alto - valor_bajo) * factor)
        # else:
        #     indice_col = obtener_indice_colesterol(col_no_hdl)
        #     if indice_col is None:
        #         return {'error': 'Colesterol no-HDL fuera de rango (3.0-7.0 mmol/L)'}
        #     riesgo = tabla[rango_edad][rango_pas][indice_col]

        else:
            indice_col = obtener_indice_colesterol(col_no_hdl)

            # Si está fuera de rango, usar el valor más cercano (extrapolación)
            if indice_col is None:
                if col_no_hdl < 3.0:
                    indice_col = 0  # Usar el valor mínimo
                    print(f"   Usando valor mínimo de la tabla (col no-HDL < 3.0)")
                elif col_no_hdl > 7.0:
                    indice_col = 3  # Usar el valor máximo
                    print(f"   Usando valor máximo de la tabla (col no-HDL > 7.0)")

            riesgo = tabla[rango_edad][rango_pas][indice_col]

    except (KeyError, IndexError):
        return {'error': 'Error al obtener el valor de riesgo'}

    if edad < 50:
        if riesgo < 2.5:
            categoria = 'Bajo'
        elif riesgo < 7.5:
            categoria = 'Moderado'
        else:
            categoria = 'Alto'
    elif edad < 70:
        if riesgo < 5:
            categoria = 'Bajo'
        elif riesgo < 10:
            categoria = 'Moderado'
        else:
            categoria = 'Alto'
    else:
        if riesgo < 7.5:
            categoria = 'Bajo'
        elif riesgo < 15:
            categoria = 'Moderado'
        else:
            categoria = 'Alto'

    return {
        'riesgo': riesgo,
        'categoria': categoria,
        'score_type': score_type.upper(),
        'region': region.upper(),
        'metodo': 'interpolado' if interpolar else 'discreto'
    }

def convertir_colesterol_mg_a_mmol(col_mg_dl):
    return col_mg_dl / 38.67

def convertir_colesterol_mmol_a_mg(col_mmol_l):
    return col_mmol_l * 38.67

